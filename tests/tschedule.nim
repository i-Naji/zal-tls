import std/[syncio, assertions]
import zal_tls/crypto/[hash, kx]
import zal_tls/keys/schedule
import hexutil, rfc8448

proc t(step, label: string): string = trace(Simple, step, label)
proc sec(s: Secret): string = toHex(s.b.toOpenArray(0, s.n - 1))

var sch = default(Schedule)
var empty = newSeq[byte](1)
assert startSchedule(sch, hashSha256, ua(empty), 0)
assert sec(sch.early) == t("{server} extract secret \"early\"", "secret")
# ECDHE from the RFC's two x25519 keys.
var cPriv = hex(t("{client} create an ephemeral x25519", "private key"))
var sPub = hex(t("{server} create an ephemeral x25519", "public key"))
var ecdhe = newSeq[byte](32)
assert x25519(ua(cPriv), ua(sPub), ua(ecdhe))
assert toHex(ecdhe) == t("{server} extract secret \"handshake\"", "IKM")
# Transcript: ClientHello, ServerHello.
var ch = hex(t("{client} construct a ClientHello", "ClientHello"))
var sh = hex(t("{server} construct a ServerHello", "ServerHello"))
var h = default(Hash)
init(h, hashSha256)
discard update(h, ua(ch), ch.len)
discard update(h, ua(sh), sh.len)
var helloHash = newSeq[byte](32)
peek(h, ua(helloHash))
assert handshakeSecrets(sch, ua(ecdhe), 32, ua(helloHash))
assert sec(sch.handshake) == t("{server} extract secret \"handshake\"", "secret")
assert sec(sch.cHs) == t("{server} derive secret \"tls13 c hs traffic\"", "expanded")
assert sec(sch.sHs) == t("{server} derive secret \"tls13 s hs traffic\"", "expanded")
var key = newSeq[byte](16)
var iv = newSeq[byte](12)
assert trafficKeys(suiteAes128Gcm, sch.sHs, ua(key), ua(iv))
assert toHex(key) == t("{server} derive write traffic keys for handshake data", "key expanded")
assert toHex(iv) == t("{server} derive write traffic keys for handshake data", "iv expanded")
# Through the server's Finished: master and application secrets.
for label in ["EncryptedExtensions", "Certificate", "CertificateVerify"]:
  var m = hex(trace(Simple, "{server} construct a" & (if label[0] == 'E': "n " else: " ") & label, label))
  discard update(h, ua(m), m.len)
var th = newSeq[byte](32)
peek(h, ua(th))
var vd = newSeq[byte](32)
assert verifyData(hashSha256, sch.sHs, ua(th), ua(vd))
var sfin = hex(t("{server} construct a Finished", "Finished"))
assert toHex(vd) == toHex(sfin.toOpenArray(4, 35))
discard update(h, ua(sfin), sfin.len)
var finHash = newSeq[byte](32)
peek(h, ua(finHash))
assert masterSecrets(sch, ua(finHash))
assert sec(sch.master) == t("{server} extract secret \"master\"", "secret")
assert sec(sch.cAp) == t("{server} derive secret \"tls13 c ap traffic\"", "expanded")
assert sec(sch.sAp) == t("{server} derive secret \"tls13 s ap traffic\"", "expanded")
assert sec(sch.exporter) == t("{server} derive secret \"tls13 exp master\"", "expanded")
assert trafficKeys(suiteAes128Gcm, sch.cAp, ua(key), ua(iv))
assert toHex(key) == t("{client} derive write traffic keys for application data", "key expanded")
wipe(sch)
echo "PASS schedule: RFC 8448 3 secrets, traffic keys, server Finished"

# The PSK side (RFC 8448 4): the ticket's PSK from section 3's resumption
# secret and the ticket nonce; the early secret, binder, early secrets.
proc r(step, label: string): string = trace(Resumed, step, label)
proc secretOf(h: string): Secret =
  var b = hex(h)
  result = default(Secret)
  result.n = b.len
  copyMem(addr result.b[0], addr b[0], b.len)
var res = secretOf(t("{client} derive secret \"tls13 res master\"", "expanded"))
var nonce = @[0'u8, 0]
var psk = ticketPsk(hashSha256, res, ua(nonce), 2)
expect(sec(psk) == t("{server} generate resumption secret \"tls13 resumption\"", "expanded"), "psk line 11")
expect(sec(psk) == r("{client} extract secret \"early\"", "IKM"), "psk line 12")
var rs = default(Schedule)
expect(startSchedule(rs, hashSha256, cast[ptr UncheckedArray[byte]](addr psk.b[0]), psk.n), "psk line 14")
expect(sec(rs.early) == r("{client} extract secret \"early\"", "secret"), "psk line 15")
let bk = binderKey(rs, true)
expect(sec(bk) == r("{client} calculate PSK binder", "PRK"), "psk line 17")
var prefix = hex(r("{client} calculate PSK binder", "ClientHello prefix"))
var ph = newSeq[byte](32)
var hp = default(Hash)
init(hp, hashSha256)
discard update(hp, ua(prefix), prefix.len)
final(hp, ua(ph))
expect(toHex(ph) == r("{client} calculate PSK binder", "binder hash"), "psk line 24")
var binder = newSeq[byte](32)
expect(verifyData(hashSha256, bk, ua(ph), ua(binder)), "psk line 26")
expect(toHex(binder) == r("{client} calculate PSK binder", "finished"), "psk line 27")
var rch = hex(nth(Resumed, "{client} send handshake record", "payload", 0))   # the whole hello (the trace's ClientHello is the prefix)
expect(toHex(rch.toOpenArray(rch.len - 32, rch.len - 1)) == toHex(binder), "the hello's own binder")
var chh = newSeq[byte](32)
init(hp, hashSha256)
discard update(hp, ua(rch), rch.len)
final(hp, ua(chh))
expect(earlySecrets(rs, ua(chh)), "psk line 34")
expect(sec(rs.cEarly) == r("{client} derive secret \"tls13 c e traffic\"", "expanded"), "psk line 35")
expect(sec(rs.earlyExporter) == r("{client} derive secret \"tls13 e exp master\"", "expanded"), "psk line 36")
expect(trafficKeys(suiteAes128Gcm, rs.cEarly, ua(key), ua(iv)), "psk line 37")
expect(toHex(key) == r("{client} derive write traffic keys for early application data", "key expanded"), "psk line 38")
expect(toHex(iv) == r("{client} derive write traffic keys for early application data", "iv expanded"), "psk line 39")
wipe(rs)
echo "PASS schedule: RFC 8448 4 ticket PSK, early secret, binder, early traffic and exporter secrets"
